(function () {
    'use strict';

    if (window.__tacoToolbarLoaded) return;
    window.__tacoToolbarLoaded = true;

    const SEARCH_URL = 'https://duckduckgo.com/html/?q=';   // used when you type something that isn't a web address
    const MAX_TABS = 9;
    const BAR_HEIGHT = 98;                                   // px the toolbar takes up at the top

    // ---------- constants ----------
    const PROXY_PREFIX = '/proxy/';
    const ASSET_PREFIX = '/__taco/';
    const NEWTAB = 'taco://newtab';
    const SETTINGS = 'taco://settings';
    const STORE_KEY = 'taco.tabs';

    const isProxied = location.pathname.startsWith(PROXY_PREFIX);
    const isTop = window.top === window;
    const nativeAlert = window.alert.bind(window);

    function onReady(fn) {
        if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', fn);
        else fn();
    }

    function getCookie(name) {
        const nameEQ = name + '=';
        const ca = document.cookie.split(';');
        for (let i = 0; i < ca.length; i++) {
            let c = ca[i];
            while (c.charAt(0) === ' ') c = c.substring(1, c.length);
            if (c.indexOf(nameEQ) === 0) return decodeURIComponent(c.substring(nameEQ.length, c.length));
        }
        return null;
    }

    // ======================================================================
    // 1. Runtime fixes for proxied pages
    // ======================================================================

    // "/proxy/https://example.com/a?b=1"  ->  "https://example.com/a?b=1"
    function targetFromLocation() {
        const rest = location.pathname.slice(PROXY_PREFIX.length) + location.search + location.hash;
        return rest.replace(/^(https?):\/+/i, '$1://');
    }

    let TARGET = isProxied ? targetFromLocation() : location.href;

    // Turns any URL a page script uses into a proxied one.
    function toProxy(u) {
        if (u === undefined || u === null) return u;
        const s = String(u);
        if (!s || s[0] === '#') return u;
        if (/^(javascript|data|blob|mailto|tel|about):/i.test(s)) return u;
        if (s.startsWith(ASSET_PREFIX) || s.startsWith(PROXY_PREFIX)) return u;
        try {
            let abs = new URL(s, TARGET).href;
            if (!/^https?:/i.test(abs)) return u;
            if (abs.startsWith(location.origin + PROXY_PREFIX) || abs.startsWith(location.origin + ASSET_PREFIX)) return abs;
            if (abs.startsWith(location.origin + '/')) {
                // built from location.origin: it meant the real site, not us
                const own = new URL(abs);
                abs = new URL(own.pathname + own.search + own.hash, TARGET).href;
            }
            return location.origin + PROXY_PREFIX + abs;
        } catch (e) {
            return u;
        }
    }

    // The reverse, so scripts reading link.href see the real address.
    function fromProxy(u) {
        const s = String(u);
        const p = location.origin + PROXY_PREFIX;
        return s.startsWith(p) ? s.slice(p.length).replace(/^(https?):\/+/i, '$1://') : u;
    }

    function installRuntime() {
        // fetch()
        const origFetch = window.fetch;
        if (origFetch) {
            window.fetch = function (input, init) {
                try {
                    if (typeof input === 'string' || input instanceof URL) input = toProxy(input);
                    else if (input instanceof Request) input = new Request(toProxy(input.url), input);
                } catch (e) { /* fall through */ }
                return origFetch.call(window, input, init);
            };
        }

        // XMLHttpRequest
        const xhrOpen = XMLHttpRequest.prototype.open;
        XMLHttpRequest.prototype.open = function (method, url, ...rest) {
            return xhrOpen.call(this, method, toProxy(url), ...rest);
        };

        // sendBeacon and window.open
        if (navigator.sendBeacon) {
            const beacon = navigator.sendBeacon.bind(navigator);
            navigator.sendBeacon = (url, data) => beacon(toProxy(url), data);
        }
        const nativeOpen = window.open;
        window.open = function (url, ...rest) {
            return nativeOpen.call(window, url ? toProxy(url) : url, ...rest);
        };

        // el.setAttribute('src', ...) and friends
        const URL_ATTRS = { href: 1, src: 1, action: 1, poster: 1, formaction: 1, data: 1 };
        const nativeSetAttribute = Element.prototype.setAttribute;
        Element.prototype.setAttribute = function (name, value) {
            if (URL_ATTRS[String(name).toLowerCase()]) value = toProxy(value);
            return nativeSetAttribute.call(this, name, value);
        };

        // img.src = ..., a.href = ..., etc.
        function hook(Cls, prop) {
            if (!Cls) return;
            const desc = Object.getOwnPropertyDescriptor(Cls.prototype, prop);
            if (!desc || !desc.get || !desc.set || !desc.configurable) return;
            Object.defineProperty(Cls.prototype, prop, {
                configurable: true,
                enumerable: desc.enumerable,
                get() { return fromProxy(desc.get.call(this)); },
                set(v) { desc.set.call(this, toProxy(v)); },
            });
        }
        hook(window.HTMLAnchorElement, 'href');
        hook(window.HTMLAreaElement, 'href');
        hook(window.HTMLLinkElement, 'href');
        hook(window.HTMLImageElement, 'src');
        hook(window.HTMLScriptElement, 'src');
        hook(window.HTMLIFrameElement, 'src');
        hook(window.HTMLMediaElement, 'src');
        hook(window.HTMLSourceElement, 'src');
        hook(window.HTMLEmbedElement, 'src');
        hook(window.HTMLFormElement, 'action');

        // history.pushState / replaceState
        ['pushState', 'replaceState'].forEach((method) => {
            const orig = history[method];
            history[method] = function (state, title, url) {
                const result = orig.call(this, state, title, url === undefined || url === null ? url : toProxy(url));
                try {
                    TARGET = targetFromLocation();
                    onLocationChange(method === 'pushState' ? 'push' : 'replace');
                } catch (e) { /* ignore */ }
                return result;
            };
        });

        // Service workers would escape the proxy, so turn them off.
        if (navigator.serviceWorker) {
            try {
                navigator.serviceWorker.register = () => Promise.reject(new Error('Service workers are disabled in Taco Proxy.'));
            } catch (e) { /* ignore */ }
        }

        // Links and forms created after the page loaded.
        document.addEventListener('click', (e) => {
            const a = e.target && e.target.closest ? e.target.closest('a[href], area[href]') : null;
            if (!a) return;
            const raw = a.getAttribute('href');
            const fixed = toProxy(raw);
            if (fixed !== raw) a.setAttribute('href', fixed);
        }, true);

        document.addEventListener('submit', (e) => {
            const form = e.target;
            if (!form || !form.getAttribute) return;
            const action = form.getAttribute('action');
            if (!action) return;
            const fixed = toProxy(action);
            if (fixed !== action) form.setAttribute('action', fixed);
        }, true);

        window.addEventListener('hashchange', () => {
            TARGET = targetFromLocation();
            onLocationChange('replace');
        });
        window.addEventListener('popstate', () => {
            TARGET = targetFromLocation();
            onLocationChange('replace');
        });
    }

    if (isProxied) installRuntime();

    // ======================================================================
    // 2. Tab cloak (title and icon chosen in Settings)
    // ======================================================================

    let pageTitle = '';        // the page's real title, before the cloak replaces it
    let titleHook = null;

    function applyCloak() {
        const title = getCookie('title') || 'Taco Proxy';
        let icon = getCookie('icon') || 'images/favicon.ico';
        if (!/^(https?:|data:|\/)/i.test(icon)) icon = ASSET_PREFIX + icon;
        const iconAttr = isProxied ? toProxy(icon) : icon;

        function enforce() {
            const head = document.head || document.documentElement;

            let t = head.querySelector('title');
            if (!t) {
                t = document.createElement('title');
                head.appendChild(t);
            }
            if (t.textContent !== title) {
                if (t.textContent.trim()) {
                    pageTitle = t.textContent.trim();
                    if (titleHook) titleHook();
                }
                t.textContent = title;
            }

            const links = head.querySelectorAll('link[rel~="icon"]');
            if (!links.length) {
                const link = document.createElement('link');
                link.setAttribute('rel', 'icon');
                link.setAttribute('href', iconAttr);
                head.appendChild(link);
            }
            links.forEach((link) => {
                if (link.getAttribute('href') !== iconAttr) link.setAttribute('href', iconAttr);
            });
        }

        enforce();
        new MutationObserver(enforce).observe(document.head || document.documentElement, {
            childList: true,
            subtree: true,
            characterData: true,
            attributes: true,
            attributeFilter: ['href'],
        });
    }

    // ======================================================================
    // 3. The toolbar (tabs + address bar)
    // ======================================================================

    let state = null;
    let root = null;
    let tabsEl, newTabBtn, backBtn, forwardBtn, address;

    function currentEntry() {
        if (isProxied) return targetFromLocation();
        return location.pathname.replace(/\/+$/, '') === '/settings.html' ? SETTINGS : NEWTAB;
    }

    function toLocation(entry) {
        if (entry === NEWTAB) return '/';
        if (entry === SETTINGS) return '/settings.html';
        return PROXY_PREFIX + entry;
    }

    function displayOf(entry) {
        return entry;   // taco://newtab, taco://settings or the real web address
    }

    function hostOf(entry) {
        try { return new URL(entry).hostname; } catch (e) { return entry; }
    }

    function entryLabel(entry) {
        if (entry === NEWTAB) return 'New Tab';
        if (entry === SETTINGS) return 'Settings';
        return pageTitle || hostOf(entry);
    }

    function makeTab(entry) {
        return {
            id: 't' + Date.now().toString(36) + Math.random().toString(36).slice(2, 6),
            title: entryLabel(entry),
            history: [entry],
            index: 0,
            replace: false,
        };
    }

    function loadState() {
        try {
            const s = JSON.parse(sessionStorage.getItem(STORE_KEY));
            if (s && Array.isArray(s.tabs) && s.tabs.length) return s;
        } catch (e) { /* ignore */ }
        const tab = makeTab(currentEntry());
        return { active: tab.id, tabs: [tab] };
    }

    function saveState() {
        try { sessionStorage.setItem(STORE_KEY, JSON.stringify(state)); } catch (e) { /* ignore */ }
    }

    function activeTab() {
        return state.tabs.find((t) => t.id === state.active) || state.tabs[0];
    }

    // Called on every page load (and when a page changes its own address).
    function syncLocation(mode) {
        if (!root) return;
        const tab = activeTab();
        const entry = currentEntry();

        if (tab.history[tab.index] !== entry) {
            if (tab.replace || mode === 'replace') {
                tab.history[tab.index] = entry;           // e.g. the site redirected
            } else {
                tab.history.length = tab.index + 1;       // new page: drop the "forward" pages
                tab.history.push(entry);
                tab.index = tab.history.length - 1;
                if (tab.history.length > 60) { tab.history.shift(); tab.index--; }
            }
        }
        tab.replace = false;
        tab.title = entryLabel(entry);
        saveState();
        renderTabs();
        updateNav();
        if (root.activeElement !== address) address.value = displayOf(entry);
    }

    function onLocationChange(mode) {
        syncLocation(mode);
    }

    function goTo(entry) {
        location.replace(toLocation(entry));
    }

    function resolveInput(raw) {
        const v = raw.trim();
        if (!v) return null;
        if (/^taco:\/\/newtab\/?$/i.test(v)) return NEWTAB;
        if (/^taco:\/\/settings\/?$/i.test(v)) return SETTINGS;
        if (/^https?:\/\//i.test(v)) return v;
        if (!/\s/.test(v) && /^(localhost|[\w-]+(\.[\w-]+)+)(:\d+)?([\/?#].*)?$/i.test(v)) return 'https://' + v;
        return SEARCH_URL + encodeURIComponent(v);
    }

    function navigate(raw) {
        const entry = resolveInput(raw);
        if (entry) location.assign(toLocation(entry));
    }

    function step(delta) {
        const tab = activeTab();
        const next = tab.index + delta;
        if (next < 0 || next >= tab.history.length) return;
        tab.index = next;
        tab.replace = true;
        saveState();
        goTo(tab.history[next]);
    }

    function switchTab(id) {
        if (id === state.active) return;
        const tab = state.tabs.find((t) => t.id === id);
        if (!tab) return;
        state.active = id;
        tab.replace = true;
        saveState();
        goTo(tab.history[tab.index]);
    }

    function newTab() {
        if (state.tabs.length >= MAX_TABS) {
            nativeAlert('The maximum number of allowed tabs is ' + MAX_TABS + '.\nJoin the Discord for updates.');
            return;
        }
        const tab = makeTab(NEWTAB);
        tab.replace = true;
        state.tabs.push(tab);
        state.active = tab.id;
        saveState();
        goTo(NEWTAB);
    }

    function closeTab(id) {
        const i = state.tabs.findIndex((t) => t.id === id);
        if (i === -1) return;
        const wasActive = id === state.active;
        state.tabs.splice(i, 1);

        if (!state.tabs.length) {                       // always keep one tab open
            const tab = makeTab(NEWTAB);
            tab.replace = true;
            state.tabs.push(tab);
            state.active = tab.id;
            saveState();
            return goTo(NEWTAB);
        }
        if (wasActive) {
            const next = state.tabs[Math.min(i, state.tabs.length - 1)];
            state.active = next.id;
            next.replace = true;
            saveState();
            return goTo(next.history[next.index]);
        }
        saveState();
        renderTabs();
        updateNav();
    }

    function reorder(fromId, toId) {
        if (!fromId || fromId === toId) return;
        const from = state.tabs.findIndex((t) => t.id === fromId);
        const to = state.tabs.findIndex((t) => t.id === toId);
        if (from === -1 || to === -1) return;
        const moved = state.tabs.splice(from, 1)[0];
        state.tabs.splice(to, 0, moved);
        saveState();
        renderTabs();
    }

    function renderTabs() {
        if (!root) return;
        tabsEl.querySelectorAll('.tab').forEach((el) => el.remove());

        state.tabs.forEach((tab) => {
            const el = document.createElement('div');
            el.className = 'tab' + (tab.id === state.active ? ' active' : '');
            el.draggable = true;

            const label = document.createElement('span');
            label.textContent = tab.title || 'New Tab';

            const close = document.createElement('button');
            close.className = 'close';
            close.title = 'Close tab';
            close.textContent = '\u00d7';

            el.appendChild(label);
            el.appendChild(close);

            el.addEventListener('click', () => switchTab(tab.id));
            close.addEventListener('click', (e) => { e.stopPropagation(); closeTab(tab.id); });
            el.addEventListener('dragstart', (e) => e.dataTransfer.setData('text/plain', tab.id));
            el.addEventListener('dragover', (e) => e.preventDefault());
            el.addEventListener('drop', (e) => {
                e.preventDefault();
                reorder(e.dataTransfer.getData('text/plain'), tab.id);
            });

            tabsEl.insertBefore(el, newTabBtn);
        });
    }

    function updateNav() {
        if (!root) return;
        const tab = activeTab();
        backBtn.disabled = tab.index <= 0;
        forwardBtn.disabled = tab.index >= tab.history.length - 1;
        newTabBtn.style.cursor = state.tabs.length >= MAX_TABS ? 'not-allowed' : 'pointer';
    }

    const ICON_LEFT = '<svg viewBox="0 0 24 24"><path d="M15 5l-7 7 7 7"/></svg>';
    const ICON_RIGHT = '<svg viewBox="0 0 24 24"><path d="M9 5l7 7-7 7"/></svg>';
    const ICON_REFRESH = '<svg viewBox="0 0 24 24"><path d="M20 12a8 8 0 1 1-2.6-5.9M20 4v5h-5"/></svg>';
    const ICON_SEARCH = '<svg viewBox="0 0 24 24"><circle cx="11" cy="11" r="6"/><path d="M16 16l5 5"/></svg>';

    const TOOLBAR_CSS = `
        :host { all: initial; position: fixed; top: 0; left: 0; right: 0; height: ${BAR_HEIGHT}px; z-index: 2147483647; display: block;
                background: #000; font-family: "IBM Plex Sans", "Segoe UI", sans-serif; }
        * { box-sizing: border-box; }
        .tabs { height: 42px; border-bottom: 2px solid blueviolet; display: flex; align-items: center; gap: 4px; padding: 0 6px;
                overflow-x: auto; overflow-y: hidden; scrollbar-width: none; }
        .tab { flex: 0 0 auto; display: flex; align-items: center; max-width: 210px; padding: 5px 10px; border-radius: 5px;
               background: #333; color: #fff; font-size: 14px; cursor: pointer; transition: transform .2s, box-shadow .2s; }
        .tab span { overflow: hidden; text-overflow: ellipsis; white-space: nowrap; max-width: 160px; }
        .tab.active { background: blueviolet; }
        .tab:hover, #newTab:hover { transform: translateY(-3px); box-shadow: 0 0 20px blueviolet; }
        .close { margin-left: 8px; padding: 0 2px; background: none; border: none; color: #fff; font-size: 16px; line-height: 1; cursor: pointer; }
        #newTab { flex: 0 0 auto; padding: 5px 10px; background: #333; color: #fff; border: none; border-radius: 5px;
                  font-size: 16px; cursor: pointer; transition: transform .2s, box-shadow .2s; }
        .bar { height: 56px; display: flex; align-items: center; gap: 8px; padding: 8px 10px; }
        .navBtn { flex: none; width: 40px; height: 40px; padding: 0; display: grid; place-items: center; border-radius: 20px;
                  border: 2px solid blueviolet; background: #000; color: #fff; font-size: 18px; cursor: pointer; }
        .navBtn:hover { background: rgba(116, 41, 185, 0.66); }
        .navBtn:active { background: blueviolet; }
        .navBtn:disabled { opacity: .35; cursor: default; background: #000; }
        svg { width: 18px; height: 18px; stroke: #fff; fill: none; stroke-width: 2.5; stroke-linecap: round; stroke-linejoin: round; }
        .search { flex: 1; min-width: 120px; height: 36px; display: flex; align-items: center; padding: 0 10px;
                  border-radius: 20px; border: 2px solid blueviolet; background: #000; }
        .search:focus-within { box-shadow: 0 0 14px blueviolet; }
        .search input { flex: 1; min-width: 0; height: 32px; background: transparent; border: none; outline: none;
                        color: #8f8f8f; font: inherit; font-size: 14px; }
        .search input:focus { color: #fff; }
        .search button { padding: 0; display: grid; place-items: center; background: none; border: none; cursor: pointer; }
    `;

    const TOOLBAR_HTML = `
        <div class="tabs" id="tabs"><button id="newTab" title="New tab">+</button></div>
        <div class="bar">
            <button class="navBtn" id="back" title="Previous Page">${ICON_LEFT}</button>
            <button class="navBtn" id="forward" title="Next Page">${ICON_RIGHT}</button>
            <button class="navBtn" id="reload" title="Refresh Page">${ICON_REFRESH}</button>
            <div class="search">
                <input id="address" placeholder="Search Taco Proxy or type a URL" autocomplete="off" autocorrect="off" autocapitalize="off" spellcheck="false">
                <button id="go" title="Go">${ICON_SEARCH}</button>
            </div>
            <button class="navBtn" id="settings" title="Settings">&#9881;</button>
        </div>
    `;

    function buildToolbar() {
        state = loadState();

        const host = document.createElement('div');
        host.id = 'taco-toolbar-host';
        root = host.attachShadow({ mode: 'open' });
        root.innerHTML = '<style>' + TOOLBAR_CSS + '</style>' + TOOLBAR_HTML;
        document.documentElement.appendChild(host);

        // push the page down so the toolbar doesn't cover it
        const offset = document.createElement('style');
        offset.textContent = 'html { margin-top: ' + BAR_HEIGHT + 'px !important; }';
        (document.head || document.documentElement).appendChild(offset);

        tabsEl = root.getElementById('tabs');
        newTabBtn = root.getElementById('newTab');
        backBtn = root.getElementById('back');
        forwardBtn = root.getElementById('forward');
        address = root.getElementById('address');

        newTabBtn.addEventListener('click', newTab);
        backBtn.addEventListener('click', () => step(-1));
        forwardBtn.addEventListener('click', () => step(1));
        root.getElementById('reload').addEventListener('click', () => location.reload());
        root.getElementById('settings').addEventListener('click', () => navigate(SETTINGS));
        root.getElementById('go').addEventListener('click', () => navigate(address.value));
        address.addEventListener('keydown', (e) => {
            if (e.key === 'Enter') { navigate(address.value); address.blur(); }
            if (e.key === 'Escape') { address.value = displayOf(currentEntry()); address.blur(); }
        });
        address.addEventListener('focus', () => address.select());

        titleHook = () => {
            if (!isProxied) return;
            activeTab().title = entryLabel(currentEntry());
            saveState();
            renderTabs();
        };

        window.addEventListener('pageshow', (e) => { if (e.persisted) syncLocation('replace'); });

        syncLocation('auto');

        window.tacoToolbar = {
            back: () => step(-1),
            forward: () => step(1),
            canGoBack: () => activeTab().index > 0,
            navigate: navigate,
            newTab: newTab,
        };
    }

    onReady(function () {
        if (!isTop) return;      // proxied pages' own iframes don't get a toolbar
        applyCloak();
        buildToolbar();
    });
})();
